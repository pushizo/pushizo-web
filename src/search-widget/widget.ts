const SEARCH_ICON =
  '<svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><circle cx="11" cy="11" r="7"/><path d="m20 20-3.5-3.5"/></svg>';
const CLOSE_ICON =
  '<svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><path d="M6 6l12 12M18 6 6 18"/></svg>';

let instances = 0;

/** Arama penceresini kurar (kapalı başlar). Dönüş: aç/kapat/yok et. */
export function mountSearchWidget(client: SearchClient, options: SearchWidgetMountOptions): SearchWidgetHandle {
  const lang = options.language.toLowerCase().startsWith('tr') ? 'tr' : 'en';
  const t: Strings = { ...SEARCH_TEXT[lang], ...(options.strings as Partial<Strings> | undefined) };
  const fmt = (template: string, vars: Record<string, string | number>) => template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  const uid = `hs-search-${++instances}`;

  const host = el('div', { 'data-pushizo-search': '', dir: options.dir, lang: options.language });
  const root = host.attachShadow({ mode: 'open' });
  root.appendChild(el('style', {}, styles(safeColor(options.color, '#2563eb'), options.theme ?? 'auto')));

  const overlay = el('div', { class: 'overlay', hidden: '' });
  const dialog = el('div', { class: 'dialog', role: 'dialog', 'aria-modal': 'true', 'aria-label': t.title });
  const bar = el('div', { class: 'bar' });
  bar.innerHTML = SEARCH_ICON;
  const input = el('input', {
    type: 'search',
    role: 'combobox',
    'aria-label': t.title,
    'aria-autocomplete': 'list',
    'aria-expanded': 'false',
    'aria-controls': `${uid}-list`,
    'aria-describedby': `${uid}-keys`,
    placeholder: options.placeholder ?? t.placeholder,
    autocomplete: 'off',
    autocapitalize: 'off',
    spellcheck: 'false',
    enterkeyhint: 'search',
    maxlength: '200',
  });
  const closeBtn = el('button', { type: 'button', class: 'icon', 'aria-label': t.close });
  closeBtn.innerHTML = CLOSE_ICON;
  bar.append(input, closeBtn);

  const body = el('div', { class: 'body' });
  const keys = el('span', { class: 'sr', id: `${uid}-keys` }, t.keys);
  const ask = el('button', { type: 'button', class: 'ask', hidden: '' });
  const askLabel = el('b', {}, t.ask);
  const askQuery = el('span');
  ask.append(askLabel, askQuery);
  const answer = el('div', { class: 'answer', 'aria-live': 'polite', hidden: '' });
  const status = el('div', { class: 'status', role: 'status', 'aria-live': 'polite' }, t.hint);
  const list = el('ul', { class: 'list', id: `${uid}-list`, role: 'listbox', 'aria-label': t.resultsLabel });
  body.append(keys, ask, answer, status, list);
  dialog.append(bar, body);
  overlay.appendChild(dialog);
  root.appendChild(overlay);
  (options.container ?? document.body).appendChild(host);

  let open = false;
  let results: SearchResult[] = [];
  let queryId = '';
  let active = -1;
  /** Yanıt verilemeyen son sorgu ("sor" düğmesi aynı sorgu için yeniden gösterilmez). */
  let answeredFor = '';
  let answersOn = options.answers ?? false;
  let seq = 0;
  let timer: ReturnType<typeof setTimeout> | null = null;
  let previousFocus: Element | null = null;

  const text = () => input.value.replace(/\s+/g, ' ').trim();
  const setActive = (index: number) => {
    active = index;
    const items = list.children;
    for (let i = 0; i < items.length; i++) items[i]!.setAttribute('aria-selected', i === index ? 'true' : 'false');
    if (index >= 0 && items[index]) {
      input.setAttribute('aria-activedescendant', items[index].id);
      (items[index] as HTMLElement).scrollIntoView?.({ block: 'nearest' });
    } else input.removeAttribute('aria-activedescendant');
  };
  const refreshAsk = () => {
    const q = text();
    const show = answersOn && q.length >= MIN_QUERY && q !== answeredFor;
    ask.hidden = !show;
    askQuery.textContent = q;
  };

  const go = (result: { url: string; title: string }, position: number, event?: Event) => {
    const url = safeUrl(result.url);
    if (!url) {
      event?.preventDefault();
      return;
    }
    void client.trackClick(queryId, url, position);
    const handled = options.onSelect?.({ url, title: result.title }) === false;
    if (handled) {
      event?.preventDefault();
      close();
      return;
    }
    // Bağlantı tıklamasında tarayıcının kendi gezinmesi çalışır (orta tık, yeni sekme kısayolları korunur).
    if (event) return;
    if (options.newTab) window.open(url, '_blank', 'noopener');
    else location.assign(url);
  };

  const renderResults = () => {
    list.replaceChildren();
    results.forEach((r, i) => {
      const href = safeUrl(r.url);
      if (!href) return;
      const item = el('li', { class: 'item', role: 'option', id: `${uid}-opt-${i}`, 'aria-selected': 'false' });
      const link = el('a', { href, tabindex: '-1' });
      if (options.newTab) {
        link.target = '_blank';
        link.rel = 'noopener';
      }
      const title = el('div', { class: 'title' }, r.title || r.url);
      if (r.heading && r.heading !== r.title) title.appendChild(el('span', { class: 'heading' }, ` › ${r.heading}`));
      const snippet = el('div', { class: 'snippet' });
      appendSnippet(snippet, r.snippet_html || r.snippet);
      link.append(title, snippet);
      link.addEventListener('click', (event) => go(r, i + 1, event));
      item.addEventListener('mousemove', () => {
        if (active !== i) setActive(i);
      });
      item.appendChild(link);
      list.appendChild(item);
    });
    input.setAttribute('aria-expanded', results.length ? 'true' : 'false');
    setActive(-1);
  };

  const renderAnswer = (res: SearchResponse) => {
    answer.replaceChildren();
    answer.hidden = false;
    if (res.answer) {
      answer.append(el('h3', {}, t.answerTitle), el('p', {}, res.answer.text));
      const sources = res.answer.sources.filter((s) => safeUrl(s.url));
      if (sources.length) {
        const ul = el('ul', { 'aria-label': t.sources });
        sources.forEach((s) => {
          const a = el('a', { href: safeUrl(s.url)! }, s.title || s.url);
          if (options.newTab) {
            a.target = '_blank';
            a.rel = 'noopener';
          }
          a.addEventListener('click', (event) => go(s, 0, event));
          const li = el('li');
          li.appendChild(a);
          ul.appendChild(li);
        });
        answer.appendChild(ul);
      }
      answer.appendChild(el('div', { class: 'note' }, t.disclaimer));
    } else answer.appendChild(el('p', {}, res.answer_status === 'not_found' ? t.notFound : t.answerUnavailable));
  };

  const run = async (mode: 'search' | 'answer') => {
    if (timer) clearTimeout(timer);
    timer = null;
    const q = text();
    const mine = ++seq;
    if (q.length < MIN_QUERY) {
      results = [];
      queryId = '';
      renderResults();
      answer.hidden = true;
      status.textContent = t.hint;
      refreshAsk();
      return;
    }
    status.textContent = mode === 'answer' ? t.answering : t.searching;
    if (mode === 'answer') {
      answeredFor = q;
      answer.hidden = true;
      refreshAsk();
    }
    try {
      const res = await client.query(q, { mode });
      // Yazmaya devam edildiyse eski yanıt atılır.
      if (mine !== seq || !open) return;
      results = res.results;
      queryId = res.query_id;
      if (options.answers === undefined) answersOn = res.answers_available;
      renderResults();
      status.textContent = results.length ? fmt(t.results, { n: results.length }) : t.noResults;
      if (mode === 'answer') renderAnswer(res);
      else if (q !== answeredFor) answer.hidden = true;
      refreshAsk();
    } catch {
      if (mine !== seq || !open) return;
      status.textContent = t.error;
    }
  };

  const schedule = () => {
    if (timer) clearTimeout(timer);
    refreshAsk();
    timer = setTimeout(() => void run('search'), DEBOUNCE_MS);
  };

  function close(): void {
    if (!open) return;
    open = false;
    seq++;
    if (timer) clearTimeout(timer);
    overlay.hidden = true;
    if (previousFocus instanceof HTMLElement) previousFocus.focus();
    previousFocus = null;
  }

  input.addEventListener('input', schedule);
  ask.addEventListener('click', () => {
    void run('answer');
    input.focus();
  });
  closeBtn.addEventListener('click', close);
  overlay.addEventListener('mousedown', (event) => {
    if (event.target === overlay) close();
  });
  dialog.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
      event.preventDefault();
      event.stopPropagation();
      close();
      return;
    }
    if (event.key === 'Tab') {
      // Odak pencerede kalır: giriş → (sor) → kapat döngüsü; sonuçlar ok tuşlarıyla gezilir.
      const stops = [input, ...(ask.hidden ? [] : [ask]), ...Array.from(answer.querySelectorAll('a')), closeBtn] as HTMLElement[];
      const current = stops.indexOf(root.activeElement as HTMLElement);
      const next = (current + (event.shiftKey ? -1 : 1) + stops.length) % stops.length;
      event.preventDefault();
      stops[current === -1 ? 0 : next]!.focus();
      return;
    }
    if (root.activeElement !== input) return;
    if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
      if (!results.length) return;
      event.preventDefault();
      const count = list.children.length;
      setActive(event.key === 'ArrowDown' ? (active + 1) % count : active <= 0 ? count - 1 : active - 1);
    } else if (event.key === 'Enter') {
      event.preventDefault();
      const chosen = active >= 0 ? results[active] : undefined;
      if (chosen) go(chosen, active + 1);
      else void run(answersOn && text() !== answeredFor ? 'answer' : 'search');
    }
  });

  const onHotkey = (event: KeyboardEvent) => {
    if ((event.ctrlKey || event.metaKey) && !event.altKey && event.key.toLowerCase() === 'k') {
      event.preventDefault();
      if (open) close();
      else handle.open();
    }
  };
  if (options.hotkey) document.addEventListener('keydown', onHotkey);

  const handle: SearchWidgetHandle = {
    open(query?: string) {
      if (!open) {
        previousFocus = document.activeElement;
        open = true;
        overlay.hidden = false;
      }
      if (query !== undefined) input.value = query.slice(0, 200);
      input.focus();
      input.select();
      if (text().length >= MIN_QUERY && (query !== undefined || !results.length)) void run('search');
      else refreshAsk();
    },
    close,
    isOpen: () => open,
    destroy() {
      close();
      document.removeEventListener('keydown', onHotkey);
      host.remove();
    },
  };
  if (options.query) input.value = options.query.slice(0, 200);
  return handle;
}
