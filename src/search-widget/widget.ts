const MIN_QUERY = 2;
const DEBOUNCE_MS = 250;

function el<K extends keyof HTMLElementTagNameMap>(tag: K, attrs: Record<string, string> = {}, text?: string): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  if (text !== undefined) node.textContent = text;
  return node;
}

/** Renk: yalnızca #rrggbb kabul edilir (CSS enjeksiyonu yok). */
function safeColor(value: string | null | undefined, fallback: string): string {
  return value && /^#[0-9a-fA-F]{6}$/.test(value) ? value : fallback;
}

/** Yalnız http(s) adresine gidilir (`javascript:` vb. reddedilir). */
function safeUrl(url: string): string | null {
  try {
    const u = new URL(url, location.href);
    return u.protocol === 'http:' || u.protocol === 'https:' ? u.toString() : null;
  } catch {
    return null;
  }
}

const ENTITIES: Record<string, string> = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'" };
const decode = (text: string): string => text.replace(/&(?:amp|lt|gt|quot|#39);/g, (m) => ENTITIES[m]!);

/** Kesiti `innerHTML` kullanmadan çizer: yalnız `<mark>` tanınır, geri kalan her şey metindir. */
function appendSnippet(parent: HTMLElement, html: string): void {
  for (const part of html.split(/(<mark>[\s\S]*?<\/mark>)/)) {
    if (!part) continue;
    const marked = /^<mark>([\s\S]*)<\/mark>$/.exec(part);
    if (marked) parent.appendChild(el('mark', {}, decode(marked[1]!)));
    else parent.appendChild(document.createTextNode(decode(part)));
  }
}

